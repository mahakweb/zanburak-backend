    public static function find(?string $code): ?array
    {
        if (! $code || ! isset(self::all()[$code])) {
            return null;
        }

        return array_merge([
            'code' => $code,
            'logo' => '/banks/'.$code.'.svg',
        ], self::all()[$code]);
    }

    /**
     * @return array{name: string, short: string, color: string, mark: string}
     */
    private static function bank(string $name, string $short, string $color, string $mark): array
    {
        return [
            'name' => $name,
            'short' => $short,
            'color' => $color,
            'mark' => $mark,
        ];
    }
